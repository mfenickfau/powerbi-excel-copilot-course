"""
Brightline Group - pick-your-domain training datasets.

Builds one Excel workbook per business domain. Every workbook has the SAME shape so a
single set of lab instructions works for all of them:

  Sheet            Role in the labs
  ---------------  --------------------------------------------------------------
  README           What the data is, column dictionary, planted-defect list
  <Fact>           One row per event. Date, three dimension keys, two numeric
                   inputs, a rate/adjustment, an Amount, and a Yes/No flag
  <Where dim>      Location-type dimension. Always has a Region column
  <What dim>       Item-type dimension. Always has a Category column
  <Who dim>        Party-type dimension. Always has a Segment column
  Targets          Year, Month, Region, Target  (for measure and variance labs)
  MessyExport      One month of the fact table, exported badly on purpose

Usage: python build_domain_workbooks.py <output_dir> [fact_rows_per_domain]
"""
import random, sys, os
from datetime import date, timedelta
import openpyxl
from openpyxl.styles import Font, PatternFill
from openpyxl.utils import get_column_letter

OUT = sys.argv[1] if len(sys.argv) > 1 else "."
TARGET_ROWS = int(sys.argv[2]) if len(sys.argv) > 2 else 1500
os.makedirs(OUT, exist_ok=True)
SEASON = {1: 0.7, 2: 0.7, 3: 0.9, 4: 1.0, 5: 1.2, 6: 1.4, 7: 1.5, 8: 1.3, 9: 1.1, 10: 0.9, 11: 1.3, 12: 1.6}
FLAT = {m: 1.0 for m in range(1, 13)}
START, END = date(2024, 1, 1), date(2025, 12, 31)
DAYS = (END - START).days + 1
HEAD_FILL = PatternFill("solid", fgColor="05192D")
HEAD_FONT = Font(bold=True, color="FFFFFF")

def pick(seq, weights=None):
    return random.choices(seq, weights=weights)[0]

def write_sheet(wb, name, headers, rows, widths=None):
    ws = wb.create_sheet(name)
    ws.append(headers)
    for c in range(1, len(headers) + 1):
        ws.cell(row=1, column=c).fill = HEAD_FILL
        ws.cell(row=1, column=c).font = HEAD_FONT
    for r in rows:
        ws.append(r)
    ws.freeze_panes = "A2"
    for i, h in enumerate(headers, 1):
        ws.column_dimensions[get_column_letter(i)].width = (widths or {}).get(h, max(12, len(h) + 2))
    return ws

def messy_rows(fact_headers, fact_rows, month_prefix, label_map):
    """Take one month of fact rows and export them badly."""
    rows = [r for r in fact_rows if r[1].strftime("%Y-%m") == month_prefix]
    rows = random.sample(rows, min(120, len(rows)))
    header = [label_map.get(h, h) for h in fact_headers]
    out = [["Brightline Group - System Export"], ["Generated by LegacyERP v4.2"], [], header]
    for i, r in enumerate(rows):
        r = list(r)
        d = r[1]
        r[1] = pick([d.strftime("%m/%d/%Y"), d.strftime("%Y-%m-%d"), f"{d.month}/{d.day}/{str(d.year)[2:]}", d.strftime("%d-%b-%Y")])
        if random.random() < 0.2: r[2] = r[2].lower() + " "            # where-key case/space
        if random.random() < 0.5: r[6] = f"${r[6]:,.2f}"                 # rate as text
        r[7] = f"{int(round(r[7]*100))}%"                                # adjustment as text percent
        if random.random() < 0.15: r[8] = None                           # missing amount
        r[9] = pick([r[9], r[9].upper(), r[9][0]])                       # Yes/No/YES/Y
        out.append(r)
        if i % 40 == 0 and i: out.append(header)
        if i % 55 == 0 and i: out.append([])
        if i % 70 == 0 and i: out.append(list(r))
    out.append([]); out.append(["TOTAL", None, None, None, None, sum(r[5] for r in rows), None, None, round(sum(r[8] for r in rows), 2), None])
    return out

def build(domain):
    random.seed(domain["seed"])
    wb = openpyxl.Workbook(); wb.remove(wb.active)
    where = domain["where"](); what = domain["what"](); who = domain["who"]()
    where_ids = [w[0] for w in where]; where_w = [w[-1] for w in where]
    fact = []
    per_day = domain.get("rows", TARGET_ROWS) / DAYS
    n = 1
    d = START
    while d <= END:
        growth = 1 + domain["growth"] * ((d - START).days / DAYS)
        k = max(0, int(round(random.gauss(per_day, per_day * 0.35) * domain["season"][d.month] * growth * domain.get("day_mult", lambda _d: 1)(d))))
        for _ in range(k):
            r = domain["row"](n, d, pick(where_ids, where_w), what, who)
            if domain.get("keep", lambda _r: True)(r):
                fact.append(r); n += 1
        d += timedelta(days=1)
    fh = domain["fact_headers"]
    write_sheet(wb, "README", ["Brightline Group training dataset"], [[l] for l in domain["readme"]] + [[""], ["Sheet", "Purpose"]] +
                [[domain["fact_name"], "Fact table: one row per " + domain["grain"]], [domain["where_name"], "Where dimension (has Region)"],
                 [domain["what_name"], "What dimension (has Category)"], [domain["who_name"], "Who dimension (has Segment)"],
                 ["Targets", "Monthly target by Region"], ["MessyExport", "One month exported badly, for the cleaning lab"]] +
                [[""], ["Column dictionary"]] + [[c, desc] for c, desc in zip(fh, domain["fact_desc"])] +
                [[""], ["Planted defects in MessyExport"], ["Title rows and a blank row above the header"], ["Header repeated every 40 rows"],
                 ["Blank rows"], ["Four date formats in one column"], ["Rate stored as text with $"], ["Adjustment stored as text percent"],
                 ["Some Amount cells blank"], ["Where-key with lowercase and trailing space"], ["Yes/No/YES/Y mixed in the flag column"],
                 ["Exact duplicate rows"], ["TOTAL row at the bottom"]], {"Brightline Group training dataset": 48})
    write_sheet(wb, domain["fact_name"], fh, fact, {"OrderDate": 12})
    for r in fact: pass
    write_sheet(wb, domain["where_name"], domain["where_headers"], [w[:-1] for w in where])
    write_sheet(wb, domain["what_name"], domain["what_headers"], what)
    write_sheet(wb, domain["who_name"], domain["who_headers"], who)
    regions = sorted({w[domain["region_col"]] for w in where})
    tot = sum(r[8] for r in fact if r[1].year == 2025)
    share = {rg: sum(r[8] for r in fact if r[1].year == 2025 and dict((w[0], w[domain["region_col"]]) for w in where)[r[2]] == rg) / tot for rg in regions}
    targets = [[2025, m, rg, int(tot * share[rg] * domain["season"][m] / sum(domain["season"].values()) * 1.06)] for m in range(1, 13) for rg in regions]
    write_sheet(wb, "Targets", ["Year", "Month", "Region", domain["target_name"]], targets)
    if "extra" in domain: domain["extra"](wb, fact, what, who)
    write_sheet(wb, "MessyExport", ["x"], [])
    ws = wb["MessyExport"]; ws.delete_rows(1)
    for r in messy_rows(fh, fact, "2025-09", domain["messy_labels"]): ws.append(r)
    for c in range(1, 11): ws.column_dimensions[get_column_letter(c)].width = 14
    # real dates
    wb[domain["fact_name"]].column_dimensions["B"].number_format = "yyyy-mm-dd"
    path = f"{OUT}/{domain['file']}"
    wb.save(path)
    print(f"{domain['file']:45s} fact rows {len(fact):5d}  {os.path.getsize(path)/1024:6.0f} KB")

